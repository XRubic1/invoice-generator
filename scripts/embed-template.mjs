/**
 * Embeds EmptyInvoice.pdf as base64 so the app never fetches it at runtime.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pdfPath = path.join(__dirname, '../src/assets/EmptyInvoice.pdf');
const outPath = path.join(__dirname, '../src/assets/templatePdfBase64.js');

const base64 = fs.readFileSync(pdfPath).toString('base64');
const output = `// Auto-generated by scripts/embed-template.mjs — do not edit\nexport default '${base64}';\n`;

fs.writeFileSync(outPath, output);
console.log(`Embedded template PDF (${base64.length} base64 chars) -> src/assets/templatePdfBase64.js`);
